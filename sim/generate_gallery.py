#!/usr/bin/env python3
"""Generate a simulator-only screen gallery from LVGL Pro generated headers."""

from __future__ import annotations

import argparse
from pathlib import Path


PORTRAIT_WIDTH = 320
PORTRAIT_HEIGHT = 480
LANDSCAPE_WIDTH = 480
LANDSCAPE_HEIGHT = 320


def screen_target(name: str) -> tuple[str, int, int]:
    if name.endswith("_landscape"):
        return "XOMCODINGUI_TARGET_LANDSCAPE", LANDSCAPE_WIDTH, LANDSCAPE_HEIGHT
    return "XOMCODINGUI_TARGET_PORTRAIT", PORTRAIT_WIDTH, PORTRAIT_HEIGHT


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ui-dir", required=True)
    parser.add_argument("--out-c", required=True)
    parser.add_argument("--out-h", required=True)
    args = parser.parse_args()

    ui_dir = Path(args.ui_dir).resolve()
    out_c = Path(args.out_c).resolve()
    out_h = Path(args.out_h).resolve()
    headers = sorted(ui_dir.glob("screens/**/*_gen.h"))

    entries = []
    for header in headers:
        screen = header.stem.removesuffix("_gen")
        target, width, height = screen_target(screen)
        include_path = header.relative_to(ui_dir).as_posix()
        entries.append((screen, include_path, target, width, height))

    out_h.write_text(
        "/* Generated by sim/generate_gallery.py. Do not edit by hand. */\n"
        "#ifndef XOMCODINGUI_SIM_SCREEN_GALLERY_GEN_H\n"
        "#define XOMCODINGUI_SIM_SCREEN_GALLERY_GEN_H\n\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "#include \"lvgl.h\"\n\n"
        "typedef lv_obj_t * (*sim_screen_create_fn_t)(void);\n\n"
        "typedef struct {\n"
        "    const char * name;\n"
        "    uint32_t target;\n"
        "    int32_t width;\n"
        "    int32_t height;\n"
        "    sim_screen_create_fn_t create;\n"
        "} sim_gallery_screen_t;\n\n"
        "extern const sim_gallery_screen_t sim_gallery_screens[];\n"
        "extern const size_t sim_gallery_screen_count;\n"
        "const sim_gallery_screen_t * sim_gallery_find_screen(const char * name);\n\n"
        "#endif /* XOMCODINGUI_SIM_SCREEN_GALLERY_GEN_H */\n",
        encoding="utf-8",
    )

    include_lines = "\n".join(f'#include "{include_path}"' for _, include_path, _, _, _ in entries)
    table_lines = "\n".join(
        f'    {{"{screen}", {target}, {width}, {height}, {screen}_create}},'
        for screen, _, target, width, height in entries
    )

    out_c.write_text(
        "/* Generated by sim/generate_gallery.py. Do not edit by hand. */\n"
        "#include \"screen_gallery_gen.h\"\n"
        "#include \"xomcodingui_gen.h\"\n"
        "#include <string.h>\n\n"
        f"{include_lines}\n\n"
        "const sim_gallery_screen_t sim_gallery_screens[] = {\n"
        f"{table_lines}\n"
        "};\n\n"
        "const size_t sim_gallery_screen_count = sizeof(sim_gallery_screens) / sizeof(sim_gallery_screens[0]);\n\n"
        "const sim_gallery_screen_t * sim_gallery_find_screen(const char * name)\n"
        "{\n"
        "    for(size_t i = 0; i < sim_gallery_screen_count; i++) {\n"
        "        if(strcmp(sim_gallery_screens[i].name, name) == 0) {\n"
        "            return &sim_gallery_screens[i];\n"
        "        }\n"
        "    }\n\n"
        "    return NULL;\n"
        "}\n",
        encoding="utf-8",
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
